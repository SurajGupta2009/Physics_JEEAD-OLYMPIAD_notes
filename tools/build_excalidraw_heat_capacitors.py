def converted_scene(slug: str, fig: Path, key: str) -> Scene:
    root=ET.parse(fig).getroot(); vb=list(map(float,root.get('viewBox','0 0 800 500').split()))
    if len(vb)!=4:raise ValueError(f'{fig}: missing viewBox')
    # Uniform scale keeps each source figure's geometry intact.
    scale=min(2.0,1360/vb[2]);offset=(32-vb[0]*scale,126-vb[1]*scale)
    global_matrix:Matrix=(scale,0,0,scale,*offset)
    vars,rules=css_rules(root)
    vars.update({'--bg':'#ffffff','--surface':'#f4f6f9','--surface-2':'#edf4fb',
                 '--accent-soft':'#e9f2fb'})
    # The extracted HTML maps omit their parent stylesheet.
    rules.update({'.t1':{'font-size':'13px','fill':INK},
                  '.t2':{'font-size':'11px','fill':MUTED},
                  '.num':{'font-size':'12px','fill':BLUE}})
    is_map=slug=='heat' and fig.stem=='fig-001'
    if is_map:
        for el in root.iter():
            if el.tag==NS+'text' and el.get('style','').find('fill:#fff')>=0:
                el.set('style','fill:'+INK)
    s=Scene(key);s.title(f'{slug.replace("-"," ").title()} · {fig.stem}',
                         'Editable companion to the local SVG; source figure is retained in the chapter.')
    def walk(el: ET.Element, mat: Matrix, inherited: dict[str,str]):
        tag=el.tag.removeprefix(NS)
        if tag in ('style','defs','marker','pattern','title','desc'):return
        if tag not in {'g','a','text','rect','circle','ellipse','line','path','polygon','polyline'}:
            raise ValueError(f'{fig}: unsupported SVG element {tag}')
        before=len(s.elements)
        style=draw_style(el,inherited,vars,rules)
        own=transform_matrix(el.get('transform',''))
        # Compose an explicit transform origin when present.
        origin=el.get('transform-origin')
        if origin and 'scale' in el.get('transform',''):
            ox,oy=(float(v) for v in origin.split())
            own=matmul(matmul((1,0,0,1,ox,oy),own),(1,0,0,1,-ox,-oy))
        mat=matmul(mat,own)
        stroke=colour(style.get('stroke','none'));fill=colour(style.get('fill','black'))
        if tag=='rect' and fill==INK:
            fill='#edf4fb';stroke=BLUE
        if is_map and tag=='path':stroke=GRID;fill='transparent'
        if is_map and tag=='text':
            style['fill']=INK
        width=float(style.get('stroke-width','1.6'))*math.hypot(mat[0],mat[1])
        dashed='stroke-dasharray' in style
        def P(x,y):return point(mat,float(x),float(y))
        if tag=='text':
            x,y=P(el.get('x','0'),el.get('y','0'))
            value=''.join(el.itertext()).strip()
            value=wording(slug,fig.stem,value)
            if (slug,fig.stem)==('heat','fig-003'):value=value.replace('∐v²∑','⟨v²⟩')
            replacements={
                'the whole course · click a branch':'the whole course',
                'every chapter opens in place':'eight chapter branches',
                'every Joule-expansion demo':'every throttling process',
                'At M=1, α=90° (plane wave)':'as M → 1⁺, α → 90°',
            }
            for old,new in replacements.items():value=value.replace(old,new)
            if value:
                size=int(max(12,min(26,float(style.get('font-size','13').removesuffix('px'))*math.hypot(mat[0],mat[1]))))
                # SVG y is the baseline, Excalidraw y is the top.
                text_w=max(80,len(value)*size*.58)
                if style.get('text-anchor')=='middle':x-=text_w/2
                if style.get('text-anchor')=='end':x-=text_w
                # Rotate around the SVG baseline anchor, not the top-left of the box.
                anchor_x,anchor_y=P(el.get('x','0'),el.get('y','0'))
                angle=math.atan2(mat[1],mat[0])
                dx=x+text_w/2-anchor_x;dy=(size*1.35+8)/2-size*.95
                cx=anchor_x+dx*math.cos(angle)-dy*math.sin(angle)
                cy=anchor_y+dx*math.sin(angle)+dy*math.cos(angle)
                s.text(cx-text_w/2,cy-(size*1.35+8)/2,value,size,colour(style.get('fill','black')),text_w)
                s.elements[-1]['angle']=angle
        elif tag=='rect':
            def length(raw,view):return view*float(raw[:-1])/100 if raw.endswith('%') else float(raw)
            x=float(el.get('x','0'));y=float(el.get('y','0'))
            w=length(el.get('width','0'),vb[2]);h=length(el.get('height','0'),vb[3])
            if w>0 and h>0:
                cx,cy=P(x+w/2,y+h/2);ww=w*math.hypot(mat[0],mat[1]);hh=h*math.hypot(mat[2],mat[3])
                s.rect(cx-ww/2,cy-hh/2,ww,hh,stroke,fill,max(1,width),bool(el.get('rx')),math.atan2(mat[1],mat[0]))
                if dashed:s.elements[-1]['strokeStyle']='dashed'
        elif tag in ('circle','ellipse'):
            cx,cy=P(el.get('cx','0'),el.get('cy','0'))
            rx=float(el.get('r',el.get('rx','0')))*math.hypot(mat[0],mat[1])
            ry=float(el.get('r',el.get('ry','0')))*math.hypot(mat[2],mat[3])
            if rx>0 and ry>0:
                s.ellipse(cx-rx,cy-ry,2*rx,2*ry,stroke,fill,max(1,width))
                s.elements[-1]['angle']=math.atan2(mat[1],mat[0])
        elif tag in ('polygon','polyline'):
            nums=[float(v) for v in re.findall(NUMBER,el.get('points',''))]
            pts=[P(*nums[i:i+2]) for i in range(0,len(nums),2)]
            add_path(s,pts+[pts[0]] if tag=='polygon' else pts,stroke,fill,width,dashed,'marker-end' in style,'marker-start' in style)
        elif tag=='line':
            p=P(el.get('x1','0'),el.get('y1','0'));q=P(el.get('x2','0'),el.get('y2','0'))
            if p!=q:add_path(s,[p,q],stroke if stroke!='transparent' else INK,'transparent',width,dashed,'marker-end' in style,'marker-start' in style)
        elif tag=='path':
            for curve in path_polylines(el.get('d','')):
                add_path(s,[P(*v) for v in curve],stroke,
                         fill if curve[0]==curve[-1] else 'transparent',width,dashed,'marker-end' in style,'marker-start' in style)
        else:
            for child in el:walk(child,mat,style)
        if tag not in ('g','a'):
            for element in s.elements[before:]:
                element['opacity']=round(100*float(style.get('opacity','1')))

    for child in root:walk(child,global_matrix,{'fill':'black','stroke':'none'})
    # Reflow long prose below the diagram rather than across adjacent panels.
    # Retain exact wording; free text is independently editable.
    if not is_map:
        import textwrap
        annotations=[e for e in s.elements[2:] if e['type']=='text' and (len(e['text'])>42 or e['text'].startswith('F = ε₀'))]
        bottom=max(e['y']+e['height'] for e in s.elements)+24
        for e in annotations:
            value='\n'.join(textwrap.wrap(e['text'],width=98,break_long_words=False))
            e.update(x=60,y=bottom,width=1250,fontSize=20,text=value,originalText=value,
                     height=27*len(value.splitlines())+8,angle=0)
            bottom+=e['height']+12
    if len(s.elements)<5:raise ValueError(f'{fig}: suspiciously empty conversion')
    return s


def plot(s, fn, xmin, xmax, x=150, y=510, w=1000, h=330, color=BLUE, steps=240):
    pts=[(x+w*i/steps,y-h*fn(xmin+(xmax-xmin)*i/steps)) for i in range(steps+1)]
    add_path(s,pts,color,'transparent',2.6)
    return pts


