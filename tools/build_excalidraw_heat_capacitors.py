def transform_matrix(raw: str) -> Matrix:
    m=IDENTITY
    for kind,args in re.findall(r'([A-Za-z]+)\s*\(([^)]+)\)',raw):
        v=[float(x) for x in re.findall(NUMBER,args)]
        if kind=='translate':op=(1,0,0,1,v[0],v[1] if len(v)>1 else 0)
        elif kind=='scale':op=(v[0],0,0,v[1] if len(v)>1 else v[0],0,0)
        elif kind=='rotate':
            a=math.radians(v[0]);co,si=math.cos(a),math.sin(a)
            op=(co,si,-si,co,0,0)
            if len(v)==3:
                op=matmul(matmul((1,0,0,1,v[1],v[2]),op),(1,0,0,1,-v[1],-v[2]))
        else:raise ValueError(f'unsupported transform: {kind}')
        m=matmul(m,op)
    return m


def draw_style(el,parent,variables,rules):
    result=base_style(el,parent,variables,rules)
    for k,v in result.items():
        result[k]=re.sub(r'var\((--[\w-]+),\s*([^)]+)\)',lambda m:variables.get(m[1],m[2]),v)
    if result.get('font-size')=='Nonepx':result['font-size']='13px'
    return result


def colour(value):
    # SVG colour-mix fills use two resolved hex colours and one percentage.
    match=re.fullmatch(r'color-mix\(in srgb,\s*(#[0-9a-fA-F]{6}) (\d+)%\s*,\s*(#[0-9a-fA-F]{6})\)',value)
    if match:
        a,p,b=match.groups();f=float(p)/100
        return '#'+''.join(f'{round(int(a[i:i+2],16)*f+int(b[i:i+2],16)*(1-f)):02x}' for i in (1,3,5))
    return base_colour(value)


