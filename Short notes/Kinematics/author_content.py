import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PAGES = []

def plain(s):
    for old, new in [('θ','theta'), ('α','alpha'), ('β','beta'),
                     ('φ','phi'), ('ω','omega'), ('ρ','rho'), ('τ','tau'), ('γ','gamma'),
                     ('Δ','delta'), ('Ω','Omega'), ('λ','lambda'), ('≥','>='), ('≈','about'),
                     ('→','to'), ('×','x'), ('−','-')]:
        s = s.replace(old, new)
    slash = chr(92)
    while slash*2 in s:
        s = s.replace(slash*2, slash)
    return s

def M(s):
    slash = chr(92)
    while slash*2 in s:
        s = s.replace(slash*2, slash)
    s = s.replace(slash + 'mathrm m', slash + 'mathrm{m}')
    s = s.replace(slash + 'mathrm s', slash + 'mathrm{s}')
    return ('m', s)
def WHY(s): return ('why', plain(s))
def WATCH(s): return ('trap', plain(s))
def CHECK(s): return ('check', plain(s))
def C(title, *items):
    cooked = []
    for x in items:
        if isinstance(x, tuple): cooked.append([x[0], x[1]])
        else: cooked.append(['p', plain(x)])
    return {'title': plain(title), 'items': cooked}
def page(section, slug, title, subtitle, takeaway, diagrams, *cards):
    assert len(cards) == 4, (slug, len(cards))
    PAGES.append({'section': section, 'slug': slug, 'title': plain(title), 'subtitle': plain(subtitle),
                  'takeaway': plain(takeaway), 'diagrams': list(diagrams), 'cards': list(cards)})

