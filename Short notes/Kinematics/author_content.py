def build():
    counts = {s: sum(p['section'] == s for p in PAGES) for s in ('JEE', 'Olympiad')}
    seen = set()
    for section in ('JEE', 'Olympiad'):
        rows = [p for p in PAGES if p['section'] == section]
        for i, p in enumerate(rows, 1):
            assert p['slug'] not in seen, p['slug']
            seen.add(p['slug'])
            p['part_page'] = i
            p['part_total'] = counts[section]
            p['source'] = ('Reference: kinematics-1d/Kinematics-1d.md and '
                           'motion-in-two-dimensions/Motion-in-two-dimensions.md; '
                           'equations independently checked')
            for c in p['cards']:
                assert len(c['items']) >= 2, c['title']
    (ROOT / 'sheets.json').write_text(json.dumps(PAGES, ensure_ascii=False, indent=2) + '\n')
    print(f"Authored {len(PAGES)} sheets: {counts['JEE']} JEE + {counts['Olympiad']} Olympiad; {sum(len(p['cards']) for p in PAGES)} cards.")

if __name__ == '__main__':
    build()
