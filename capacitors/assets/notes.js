/* Shared behaviour for a notes topic (see STRUCTURE.md): TOC, theme, progress, navigation.
   - injects SVG marker/def sprite (arrowheads)
   - builds the sidebar TOC from h2/h3 (auto-ids) + active-section highlight
   - theme toggle, reading progress, print, expand/collapse all solutions
   - auto prev/next footer navigation
   - "solved" state per question and per-chapter ticks, remembered in localStorage
   Dependency-free; works from file:// and needs no CDN. */
(function () {
  "use strict";

  /* ---------- page order ---------- */
  /* Topic identity and page order come from assets/pages.js (generated — see tools/setpages.py).
     Everything below has a fallback so a page still works if that file is missing. */
  var SITE = window.NOTES_SITE || {};

  /* Page order comes from assets/pages.js (generated by tools/setpages.py). The list below is a
     fallback for a page opened without it, so nothing ever renders without navigation. */
  var FALLBACK_PAGES = [
    ["index.html", "Home · syllabus map"],
    ["01-foundations.html", "1 · Charge, conductors & Gauss"],
    ["02-capacitance.html", "2 · Capacitance & every geometry"],
    ["03-energy-and-force.html", "3 · Energy, force & pressure"],
    ["04-combinations.html", "4 · Combinations & networks"],
    ["05-dielectrics.html", "5 · Dielectrics"],
    ["06-networks-and-transients.html", "6 · DC networks & RC transients"],
    ["07-advanced-topics.html", "7 · Advanced / Olympiad toolkit"],
    ["08-playbook.html", "8 · Playbook & traps"],
    ["09-olympiad-paper.html", "9 · Olympiad paper (36 Q)"],
    ["10-olympiad-solutions.html", "10 · Full solutions"],
    ["11-formula-sheet.html", "11 · Formula sheet"]
  ];

  var PAGES = window.NOTES_PAGES || FALLBACK_PAGES;

  var LS = SITE.ls || "notes:";
  function get(k, d) { try { var v = localStorage.getItem(LS + k); return v === null ? d : JSON.parse(v); } catch (e) { return d; } }
  function set(k, v) { try { localStorage.setItem(LS + k, JSON.stringify(v)); } catch (e) {} }
  function page() { return location.pathname.split("/").pop() || "index.html"; }
  function idx() { var i = -1; PAGES.forEach(function (p, j) { if (p[0] === page()) i = j; }); return i; }

  /* ---------- svg defs ---------- */
  var DEFS =
    '<svg class="sprite" aria-hidden="true"><defs>' +
    '<marker id="ah" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">' +
    '<path d="M0,1 L9.6,5 L0,9 Z" fill="var(--fg)"></path></marker>' +
    '<marker id="ahb" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">' +
    '<path d="M0,1 L9.6,5 L0,9 Z" fill="var(--accent)"></path></marker>' +
    '<marker id="ahr" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">' +
    '<path d="M0,1 L9.6,5 L0,9 Z" fill="var(--neg)"></path></marker>' +
    '<marker id="ahg" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">' +
    '<path d="M0,1 L9.6,5 L0,9 Z" fill="var(--pos)"></path></marker>' +
    '<marker id="aho" viewBox="0 0 10 10" refX="8.6" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">' +
    '<path d="M1,1.4 L8.6,5 L1,8.6" fill="none" stroke="var(--fg)" stroke-width="1.8"></path></marker>' +
    '<marker id="dim" viewBox="0 0 8 12" refX="4" refY="6" markerWidth="7" markerHeight="10" orient="auto">' +
    '<path d="M4,0 L4,12" stroke="var(--muted)" stroke-width="1.1"></path></marker>' +
    '</defs></svg>';

  /* ---------- headings + toc ---------- */
  function slug(t, i) {
    var s = String(t).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 46);
    return "s-" + (s || "h") + "-" + i;
  }
  function buildTOC() {
    var main = document.querySelector("main") || document.body;
    var hs = [].slice.call(main.querySelectorAll("h2,h3")).filter(function (h) { return !h.closest(".ex,.q,.box"); });
    hs.forEach(function (h, i) { if (!h.id) h.id = slug(h.textContent.replace(/^\s*\d+([.·]\s*\d+)?\s*/, ""), i); });
    var toc = document.getElementById("toc");
    if (toc && hs.length) {
      var ol = document.createElement("ol");
      hs.forEach(function (h) {
        var li = document.createElement("li"), a = document.createElement("a");
        a.href = "#" + h.id;
        a.textContent = h.textContent.replace(/\s+/g, " ").trim();
        if (h.tagName === "H3") a.className = "l3";
        li.appendChild(a); ol.appendChild(li);
      });
      toc.appendChild(ol);

      var byId = {};
      [].slice.call(toc.querySelectorAll("a")).forEach(function (a) { byId[a.getAttribute("href").slice(1)] = a; });
      if ("IntersectionObserver" in window) {
        var io = new IntersectionObserver(function (es) {
          var best = null;
          es.forEach(function (e) { if (e.isIntersecting && (!best || e.boundingClientRect.top < best.boundingClientRect.top)) best = e; });
          if (!best) return;
          var a = byId[best.target.id]; if (!a) return;
          [].slice.call(toc.querySelectorAll("a.on")).forEach(function (x) { x.classList.remove("on"); });
          a.classList.add("on");
        }, { rootMargin: "0px 0px -75% 0px", threshold: 0 });
        hs.forEach(function (h) { io.observe(h); });
      }
    }
  }

  function expandAll(open) { [].slice.call(document.querySelectorAll("main details")).forEach(function (d) { d.open = open; }); }

  /* ---------- top bar ---------- */
  function initBar() {
    var i = idx();
    var bar = document.createElement("div");
    bar.className = "topbar";
    bar.innerHTML =
      '<div class="in">' +
      '<a class="brand" href="index.html" style="border:0">⚡ <span>' + (SITE.brand || "Notes") + '</span></a>' +
      '<span class="crumb">' + (i > 0 ? PAGES[i][1] : "") + "</span>" +
      '<span class="sp"></span>' +
      "</div>";
    document.body.insertBefore(bar, document.body.firstChild);
    var inr = bar.querySelector(".in");

    var theme = document.createElement("button");
    theme.className = "btn"; theme.type = "button";
    function paintTheme() { theme.textContent = document.documentElement.dataset.theme === "dark" ? "☀ Light" : "🌙 Dark"; }
    theme.onclick = function () {
      var nx = document.documentElement.dataset.theme === "dark" ? "light" : "dark";
      document.documentElement.dataset.theme = nx; set("theme", nx); paintTheme();
    };
    paintTheme(); inr.appendChild(theme);

    var all = document.createElement("button");
    all.className = "btn"; all.type = "button"; all.textContent = "▾ Solutions";
    all.onclick = function () {
      var open = !!document.querySelector("main details:not([open])");
      expandAll(open); all.textContent = open ? "▸ Solutions" : "▾ Solutions";
    };
    if (document.querySelector("main details")) inr.appendChild(all);

    var pr = document.createElement("button");
    pr.className = "btn"; pr.type = "button"; pr.textContent = "🖨 Print";
    pr.onclick = function () { expandAll(true); window.print(); };
    inr.appendChild(pr);

    var pb = document.createElement("div"); pb.id = "progress"; document.body.appendChild(pb);
    function upd() {
      var h = document.documentElement.scrollHeight - window.innerHeight;
      pb.style.width = (h > 8 ? Math.min(100, window.scrollY / h * 100) : 0) + "%";
    }
    addEventListener("scroll", upd, { passive: true }); addEventListener("resize", upd); upd();

    if (location.hash) {
      var t = document.getElementById(decodeURIComponent(location.hash.slice(1)));
      if (t) setTimeout(function () { t.scrollIntoView(); }, 60);
    }
  }

  /* ---------- footer nav ---------- */
  function initNav() {
    var i = idx(), host = document.querySelector("main .pagenav");
    if (!host) { host = document.createElement("div"); host.className = "pagenav"; (document.querySelector("main") || document.body).appendChild(host); }
    var pv = i > 0 ? PAGES[i - 1] : null, nx = i >= 0 && i < PAGES.length - 1 ? PAGES[i + 1] : null;
    host.innerHTML =
      (pv ? '<a href="' + pv[0] + '"><small>← previous</small>' + pv[1].replace(/^\d+ · /, "") + "</a>"
          : '<a href="#top"><small>↑</small>Top of page</a>') +
      (nx ? '<a class="nx" href="' + nx[0] + '"><small>next →</small>' + nx[1].replace(/^\d+ · /, "") + "</a>"
          : '<a class="nx" href="index.html"><small>done →</small>Syllabus map</a>');
  }

  /* ---------- "mark solved" on every question ---------- */
  function initSolved() {
    var qs = [].slice.call(document.querySelectorAll("main .q"));
    if (!qs.length) return;
    var key = "solved:" + page(), st = get(key, {}), tot = document.getElementById("solvedCount");

    qs.forEach(function (q, i) {
      if (!q.id) q.id = "q" + (i + 1);
      var hd = q.querySelector(".hd"); if (!hd) return;
      var b = document.createElement("button");
      b.className = "btn"; b.type = "button";
      b.style.cssText = "margin-left:auto;font-size:.72rem;padding:.22rem .5rem";
      b.title = "Remember that you solved this question (saved in this browser)";
      b.onclick = function () {
        if (st[q.id]) delete st[q.id]; else st[q.id] = 1;
        set(key, st); paint(b, q); tally();
      };
      hd.appendChild(b);
      paint(b, q);
    });

    function paint(b, q) {
      var on = !!st[q.id];
      b.textContent = on ? "✓ solved" : "○ mark";
      b.style.borderColor = on ? "var(--pos)" : "var(--rule)";
      b.style.color = on ? "var(--pos)" : "var(--muted)";
      b.style.background = on ? "color-mix(in srgb,var(--pos) 12%,var(--panel))" : "var(--panel)";
    }
    function tally() {
      var c = qs.filter(function (q) { return st[q.id]; }).length;
      if (tot) tot.textContent = c + " / " + qs.length;
    }
    tally();
  }

  /* ---------- index page: chapter ticks + progress ---------- */
  function initIndex() {
    var cards = [].slice.call(document.querySelectorAll("[data-chk]"));
    if (!cards.length) return;
    cards.forEach(function (el) {
      var k = "chk:" + el.getAttribute("data-chk");
      if (get(k, false)) { el.classList.add("done"); var s0 = el.querySelector(".st"); if (s0) s0.textContent = "✓ done"; }
      el.addEventListener("click", function (e) {
        var a = e.target.closest ? e.target.closest("a") : null;
        if (a && a.classList.contains("go")) return;           /* real link click */
        e.preventDefault();
        var on = !el.classList.contains("done");
        el.classList.toggle("done", on); set(k, on);
        var s = el.querySelector(".st"); if (s) s.textContent = on ? "✓ done" : "→";
        tally();
      });
    });
    function tally() {
      var d = cards.filter(function (c) { return c.classList.contains("done"); }).length;
      var t = document.getElementById("overall"); if (t) t.textContent = d + " / " + cards.length;
      var bar = document.getElementById("overallbar"); if (bar) bar.style.height = "100%";
      if (bar) bar.style.width = (cards.length ? 100 * d / cards.length : 0) + "%";
    }
    tally();
  }

  /* ---------- boot ---------- */
  function boot() {
    var saved = get("theme", null);
    if (saved) document.documentElement.dataset.theme = saved;
    else if (window.matchMedia && matchMedia("(prefers-color-scheme: dark)").matches) document.documentElement.dataset.theme = "dark";
    var d = document.createElement("div"); d.innerHTML = DEFS;
    document.body.insertBefore(d.firstChild, document.body.firstChild);
    initBar(); buildTOC(); initNav(); initSolved(); initIndex();
    var mt = document.getElementById("tocToggle");
    if (mt) mt.onclick = function () {
      var t = document.getElementById("toc"); if (!t) return;
      var hid = t.hasAttribute("hidden");
      if (hid) t.removeAttribute("hidden"); else t.setAttribute("hidden", "");
      mt.textContent = hid ? "Hide contents" : "Show contents";
    };
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot); else boot();
})();
